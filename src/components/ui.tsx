/** Small labelled meter (0–1). */
export function Meter({ label, value, tone }: { label: string; value: number; tone: "lavender" | "sky" | "sage" }) {
  const bar = { lavender: "bg-lavender-400", sky: "bg-sky-300", sage: "bg-sage-300" }[tone];
  const pct = Math.round(Math.max(0, Math.min(1, value)) * 100);
  return (
    <div>
      <div className="mb-1 flex justify-between text-xs text-ink-500">
        <span>{label}</span>
        <span className="tabular-nums">{pct}%</span>
      </div>
      <div className="h-1.5 overflow-hidden rounded-full bg-cream" role="meter" aria-label={label} aria-valuemin={0} aria-valuemax={100} aria-valuenow={pct}>
        <div className={cx("h-full rounded-full", bar)} style={{ width: `${pct}%` }} />
      </div>
    </div>
  );
}

